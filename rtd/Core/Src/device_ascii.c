#include "device_ascii.h"
#include <stdio.h>

// Формирование строки с сырыми кодами АЦП первых четырёх каналов, разделёнными пробелами
size_t device_ascii_format(const device_frame_t *f, char *buffer, size_t capacity)
{
    // Массив для хранения подготовленных значений 4 каналов (знаковый тип нужен для вывода -1 при
    // ошибке)
    int v[4];
    int length; // Переменная для результата работы функции snprintf (число записанных символов)
    unsigned i; // Счётчик цикла по четырём каналам
    if (!f || !buffer || !capacity) return 0; // Защита от нулевых указателей и буфера нулевой длины
    for (i = 0; i < 4; ++i) // Проходим по первым четырём каналам кадра (индексы 0..3)
        // Если канал исправен, берём его 15-битный код АЦП, иначе подставляем маркер ошибки -1
        v[i] = f->channel[i].status == DEVICE_VALID ? (int)f->channel[i].sample.raw : -1;
    // Форматируем 4 числа через пробел с переводом строки CRLF в выходной буфер
    length = snprintf(buffer, capacity, "%d %d %d %d\r\n", v[0], v[1], v[2], v[3]);
    // Возвращаем длину строки без учёта терминатора '\0', либо 0, если строка была обрезана из-за
    // нехватки буфера
    return length > 0 && (size_t)length < capacity ? (size_t)length : 0;
}
