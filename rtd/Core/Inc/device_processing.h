#ifndef DEVICE_PROCESSING_H
#define DEVICE_PROCESSING_H

#include <stdint.h>

// Структура хранения состояния цифровых фильтров одного измерительного канала
typedef struct {
    uint16_t median[7]; // Кольцевой буфер последних сырых отсчётов АЦП для медианного фильтра (до максимального окна 7)
    uint16_t average[16]; // Кольцевой буфер отсчётов после медианы для фильтра скользящего среднего (до максимального окна 16)
    uint32_t sum; // Текущая бегущая сумма элементов в окне скользящего среднего (позволяет не пересчитывать сумму в цикле)
    uint8_t median_pos; // Индекс текущей ячейки записи в кольцевом буфере медианного фильтра
    uint8_t median_count; // Фактическое число накопленных отсчётов в окне медианы (растёт от 0 до median_window при прогреве)
    uint8_t average_pos; // Индекс текущей ячейки записи в кольцевом буфере скользящего среднего
    uint8_t average_count; // Фактическое число накопленных отсчётов в окне усреднения (растёт от 0 до average_window)
} device_filter_t; // Имя типа структуры истории фильтров канала

// Структура параметров фильтрации и калибровки, передаваемая на вход вычислителя для одного канала
typedef struct {
    uint8_t median_window; // Заданная длина окна медианного фильтра (допустимы значения 3, 5 или 7)
    uint8_t average_window; // Заданная длина окна скользящего среднего (допустимы степени двойки: 2, 4, 8 или 16)
    uint8_t use_median; // Логический флаг: 1 — выполнять медианную фильтрацию, 0 — пропускать сырой отсчёт напрямую
    uint8_t use_average; // Логический флаг: 1 — выполнять скользящее усреднение, 0 — не усреднять
    uint8_t use_calibration; // Логический флаг: 1 — применять смещение АЦП (adc_offset) и коэффициент наклона (gain)
    int32_t adc_offset; // Индивидуальная знаковая поправка кода АЦП (b) в единицах исходного 15-битного кода
    float r0; // Номинальное сопротивление термометра при 0 °C в Омах (100.0 или 1000.0 Ом)
    float rref; // Фактическое сопротивление опорного резистора канала в Омах
    float gain; // Безразмерный калибровочный множитель наклона температурной характеристики (k)
} device_processing_settings_t; // Имя типа структуры настроек обработки канала

// Структура выходных результатов математической обработки одного отсчёта канала
typedef struct {
    uint32_t adc_q1; // Отфильтрованный код АЦП в формате с фиксированной точкой Q1 (удвоенный код в диапазоне 0..65534) до калибровки
    uint32_t corrected_q1; // Код АЦП в формате Q1 после прибавления удвоенного калибровочного смещения 2*b
    float resistance; // Вычисленное физическое сопротивление датчика в Омах
    float temperature; // Вычисленная температура датчика в градусах Цельсия (с учётом коэффициента gain)
    uint8_t valid; // Флаг достоверности результата: 1 — расчёт успешен и фильтры прогреты, 0 — данные нельзя использовать
} device_processed_t; // Имя типа структуры результатов обработки

void device_filter_reset(device_filter_t *); // Прототип функции обнуления буферов и счётчиков фильтра канала
int device_filter_valid(const device_processing_settings_t *); // Прототип функции проверки корректности окон и коэффициентов
int device_process(device_filter_t *, const device_processing_settings_t *, uint16_t, device_processed_t *); // Прототип конвейера обработки отсчёта (возвращает 1 — норма, 0 — прогрев окна, -1 — ошибка)
int device_cvd_temperature(float resistance, float r0, float *temperature); // Прототип функции расчёта температуры по уравнению Каллендара — Ван Дюзена

#endif
