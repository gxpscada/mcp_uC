#ifndef REGISTER_MAP_H
#define REGISTER_MAP_H

#define COIL_RUN 0u // Адрес Coil 0: запуск (1) и остановка (0) цикла опроса датчиков MAX31865
#define COIL_SAVE 1u // Адрес Coil 1: команда сохранения текущих настроек из ОЗУ в журнал Flash-памяти
#define COIL_CLEAR 2u // Адрес Coil 2: команда сброса защёлкнутых аппаратных ошибок датчиков и кода ошибки прибора
#define COIL_RTC 3u // Адрес Coil 3: команда записи подготовленного времени из HR_RTC_LO/HI в аппаратные часы RTC
#define COIL_REBOOT 4u // Адрес Coil 4: команда программной перезагрузки микроконтроллера через NVIC_SystemReset
#define COIL_DEFAULTS 5u // Адрес Coil 5: команда сброса рабочих настроек в ОЗУ к заводским значениям по умолчанию
#define COIL_MEDIAN 6u // Адрес Coil 6: флаг включения (1) / отключения (0) медианного фильтра по всем каналам
#define COIL_AVERAGE 7u // Адрес Coil 7: флаг включения (1) / отключения (0) фильтра скользящего среднего
#define COIL_CALIBRATION 8u // Адрес Coil 8: флаг включения (1) / отключения (0) калибровочных коэффициентов b и k
#define COIL_COUNT 9u // Общее количество поддерживаемых битовых флагов в пространстве Coils (адреса 0..8)

#define DEVICE_CMD_SAVE (1u << COIL_SAVE) // Битовая маска внутренней команды сохранения настроек во Flash (бит 1)
#define DEVICE_CMD_CLEAR (1u << COIL_CLEAR) // Битовая маска внутренней команды очистки флагов ошибок (бит 2)
#define DEVICE_CMD_RTC (1u << COIL_RTC) // Битовая маска внутренней команды установки времени RTC (бит 3)
#define DEVICE_CMD_REBOOT (1u << COIL_REBOOT) // Битовая маска внутренней команды перезагрузки МК (бит 4)
#define DEVICE_CMD_DEFAULTS (1u << COIL_DEFAULTS) // Битовая маска внутренней команды загрузки заводских настроек (бит 5)

#define HR_CHANNELS 0u // Адрес Holding-регистра 0: количество активных опрашиваемых каналов (1..DEVICE_BOARD_CHANNEL_COUNT)
#define HR_RREF 1u // Базовый адрес блока Holding-регистров 1..8: опорные сопротивления Rref каналов 0..7 (в десятых долях Ома, Rref * 10)
#define HR_OFFSET 9u // Базовый адрес блока Holding-регистров 9..16: знаковые смещения кода АЦП b каналов 0..7 (int16 в дополнительном коде)
#define HR_GAIN 0x11u // Базовый адрес блока Holding-регистров 17..24 (0x11..0x18): коэффициенты наклона k каналов 0..7 (в сотых долях, k * 100)
#define HR_AVERAGE 0x19u // Адрес Holding-регистра 25 (0x19): длина окна фильтра скользящего среднего (2, 4, 8 или 16)
#define HR_MEDIAN 0x1au // Адрес Holding-регистра 26 (0x1A): длина окна медианного фильтра (3, 5 или 7)
#define HR_RTC_LO 0x1bu // Адрес Holding-регистра 27 (0x1B): младшие 16 бит нового значения времени Unix UTC для установки часов
#define HR_RTC_HI 0x1cu // Адрес Holding-регистра 28 (0x1C): старшие 16 бит нового значения времени Unix UTC для установки часов
#define HR_CHANNEL_MASK 0x1du // Битовая маска выбранных каналов.
#define DEVICE_HOLDING_COUNT 30u // Общее количество непрерывных регистров в области Holding Registers (адреса 0..29)

#define IR_RUNTIME_LO 1u // Адрес Input-регистра 1: младшие 16 бит времени работы текущего сеанса измерений в миллисекундах
#define IR_RUNTIME_HI 2u // Адрес Input-регистра 2: старшие 16 бит времени работы текущего сеанса измерений в миллисекундах
#define IR_STATUS 9u // Базовый адрес блока Input-регистров 9..16: Fault Status MAX31865 каналов 0..7; старший байт всегда нулевой
#define IR_TEMPERATURE 0x15u // Базовый адрес блока Input-регистров 21..28 (0x15..0x1C): температура каналов 0..7 в сотых долях °C (знаковый int16, T * 100)
#define IR_ERROR 0x1du // Адрес Input-регистра 29 (0x1D): код последней ошибки протокола или оборудования (0 — нет, 1 — адрес, 2 — значение, 4 — сбой прибора)
#define IR_RTC_LO 0x1eu // Адрес Input-регистра 30 (0x1E): младшие 16 бит штампа времени UTC текущего кадра измерений
#define IR_RTC_HI 0x1fu // Адрес Input-регистра 31 (0x1F): старшие 16 бит штампа времени UTC текущего кадра измерений
#define IR_ADC 0x20u // Базовый адрес блока Input-регистров 32..39 (0x20..0x27): сырые 15-битные коды АЦП каналов 0..7 без фильтрации
#define IR_HW 0x35u // Адрес Input-регистра 53 (0x35): номер аппаратной ревизии печатной платы
#define IR_SW 0x36u // Адрес Input-регистра 54 (0x36): номер версии встроенного ПО (например, 0x0300 для версии 3.0)
#define DEVICE_INPUT_COUNT 0x70u // Размер массива снимка Input-регистров, включая программные статусы и Q1

#define REGISTER_INVALID_T 0x8000u // Специальный маркер недостоверной температуры в 16-битном регистре (-32768 в дополнительном коде)
#define REGISTER_INVALID_ADC 0xffffu // Специальный маркер недостоверного отсчёта в регистре сырого кода АЦП (65535, выходит за 15-битный диапазон)
#define REGISTER_RREF_SCALE 10.0f // Масштабный множитель для перевода сопротивления Rref из Омов в целые единицы регистра Modbus (шаг 0.1 Ом)
#define REGISTER_GAIN_SCALE 100.0f // Масштабный множитель для перевода коэффициента наклона k в целые единицы регистра Modbus (шаг 0.01)
#define REGISTER_T_SCALE 100.0f // Масштабный множитель для представления температуры в 16-битном регистре в сотых долях градуса (шаг 0.01 °C)

#define IR_TEMPERATURE_FLOAT 0x40u // Базовый адрес расширенного блока Input-регистров 64..79 (0x40..0x4F): температура каналов 0..7 в формате IEEE 754 float32 (по 2 регистра на канал)
#define IR_RESISTANCE_FLOAT 0x50u // Базовый адрес расширенного блока Input-регистров 80..95 (0x50..0x5F): сопротивление каналов 0..7 в Омах в формате IEEE 754 float32
#define IR_SOFTWARE_STATUS 0x60u // Программные статусы каналов, отдельно от Fault Status.
#define IR_ADC_Q1 0x68u // Усреднённый код с шагом 0.5 отсчёта; 0xFFFF — недостоверен.
#define IR_FLOAT_END 0x60u
#define IR_EXT_END 0x70u // Верхняя граница расширенной области Input-регистров (не включительно)

#endif
