#ifndef DEVICE_STORE_H
#define DEVICE_STORE_H

#include "device_types.h"
#include <stddef.h>
#include <stdint.h>

#define DEVICE_STORE_WORDS 20u // Фиксированный размер одной записи (слота) в журнале Flash в 32-битных словах (20 слов = 80 байт)

// Структура контекста платформонезависимого журнала хранения настроек во Flash-памяти
typedef struct {
    const volatile uint32_t *memory; // Указатель на базовый адрес выделенного сектора Flash для прямого чтения слов
    size_t word_count; // Полная ёмкость выделенного сектора Flash в 32-битных словах
    size_t next_slot; // Смещение (в 32-битных словах от начала сектора) первого чистого слота для следующей записи
    uint32_t record[DEVICE_STORE_WORDS]; // Буфер в ОЗУ, содержащий подготовленный 20-словный образ записи (заголовок, данные, CRC и маркер COMMIT)
    uint8_t state; // Состояние автомата записи: 0 — покой, 1 — запуск записи очередного слова, 2 — ожидание завершения программирования слова
    uint8_t index; // Индекс текущего программируемого слова внутри массива record (от 0 до 18)
    uint8_t error; // Флаг ошибки: 1 — переполнение сектора, ошибка контроллера Flash или несовпадение при контрольном чтении
    void *context; // Непрозрачный указатель пользовательского контекста для платформенных колбэков Flash
    int (*begin_word)(void *, size_t, uint32_t); // Callback-функция разблокировки Flash и старта записи одного 32-битного слова по смещению
    int (*poll_word)(void *); // Callback-функция проверки статуса записи слова (0 — занято, 1 — успешно записано, -1 — аппаратная ошибка/таймаут)
} device_store_t; // Имя типа структуры контекста журнала

int device_store_load(device_store_t *, device_config_t *); // Прототип функции сканирования сектора Flash и восстановления последней валидной конфигурации
int device_store_save(device_store_t *, const device_config_t *); // Прототип функции подготовки снимка конфигурации и запуска пошагового сохранения в новый слот
void device_store_poll(device_store_t *); // Прототип неблокирующей функции продвижения пословной записи во Flash из главного цикла

#endif
