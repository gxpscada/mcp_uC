#ifndef DEVICE_TYPES_H
#define DEVICE_TYPES_H

#include <stdint.h>
#include <string.h>
#include <float.h>
#include "device_board.h"
#include "device_config.h"

// Объединение для работы с 32-битными величинами и их представлениями в памяти
typedef union {
    uint32_t u32; // Беззнаковое 32-битное целое (используется для штампов Unix-времени и битовых операций)
    int32_t i32; // Знаковое 32-битное целое в дополнительном коде
    float f32; // Вещественное число одинарной точности стандарта IEEE 754 (binary32)
    uint16_t words[2]; // Представление в виде двух 16-битных полуслов в нативном порядке байтов ядра (Little-Endian на ARM Cortex-M)
    uint8_t bytes[4]; // Побайтовое представление 32-битного слова в памяти
} device_value32_t; // Имя типа универсального 32-битного контейнера

// Статическая проверка на этапе компиляции: убеждаемся, что тип float занимает ровно 4 байта и строго соответствует стандарту IEEE 754 binary32 (основание 2, мантисса 24 бита, макс. экспонента 128)
_Static_assert(sizeof(float) == 4 && sizeof(device_value32_t) == 4 && FLT_RADIX == 2 && FLT_MANT_DIG == 24 && FLT_MAX_EXP == 128, "IEEE754 binary32 required");

// Статическая проверка на этапе компиляции: число активных каналов по умолчанию не должно быть меньше 1 или превышать количество физически распаянных датчиков на плате
_Static_assert(DEVICE_DEFAULT_CHANNELS >= 1 && DEVICE_DEFAULT_CHANNELS <= DEVICE_BOARD_CHANNEL_COUNT, "Active channels exceed physical board");

// Структура рабочей конфигурации прибора в физических единицах (используется в расчётах и сохраняется во Flash)
typedef struct {
    uint32_t active_channels; // Текущее количество опрашиваемых активных каналов (от 1 до DEVICE_BOARD_CHANNEL_COUNT)
    float r0[DEVICE_MAX_CHANNELS]; // Номинальные сопротивления датчиков при 0 °C для каждого канала в Омах (например, 1000.0 Ом для Pt1000)
    float rref[DEVICE_MAX_CHANNELS]; // Фактические сопротивления опорных резисторов Rref для каждого канала в Омах
    int32_t adc_offset[DEVICE_MAX_CHANNELS]; // Индивидуальные знаковые калибровочные поправки нуля АЦП (коэффициент b) в отсчётах 15-битного АЦП
    float gain[DEVICE_MAX_CHANNELS]; // Индивидуальные калибровочные множители наклона температурной характеристики (коэффициент k)
    uint32_t average_window; // Длина окна фильтра скользящего среднего в отсчётах (2, 4, 8 или 16)
    uint32_t median_window; // Длина окна медианного фильтра в отсчётах (3, 5 или 7)
    uint32_t rtc_pending; // Буфер подготовленного 32-битного значения времени Unix UTC (собирается из регистров HR_RTC_LO и HR_RTC_HI перед командой установки часов)
    uint8_t use_median; // Флаг разрешения медианной фильтрации (1 — включена, 0 — выключена)
    uint8_t use_average; // Флаг разрешения фильтра скользящего среднего (1 — включён, 0 — выключен)
    uint8_t use_calibration; // Флаг разрешения калибровки по коэффициентам adc_offset и gain (1 — включена, 0 — выключена)
} device_config_t; // Имя типа структуры рабочей конфигурации

#endif
