#ifndef DEVICE_ACQUISITION_H
#define DEVICE_ACQUISITION_H

#include "max31865_driver.h" // Подключаем типы драйвера датчика MAX31865 и структуру отсчёта max31865_sample_t
#include "device_types.h" // Подключаем базовые общие типы и константы размерности массивов

typedef unsigned device_trigger_t; // Тип для задания политики ожидания готовности каналов при сборке кадра
#define DEVICE_WAIT_ALL 0u // Штатный режим: кадр формируется только когда все активные каналы выставили сигнал DRDY (либо вышел таймаут)
#define DEVICE_TRIGGER_FIRST 1u // Экспериментальный режим: чтение всех каналов начинается сразу по готовности DRDY нулевого канала

#define DEVICE_VALID 0u // Статус канала (0x00): отсчёт АЦП успешно прочитан, аппаратных и программных ошибок нет
#define DEVICE_NOT_READY 1u // Бит статуса (0x01): к моменту чтения кадра датчик не выставил низкий уровень готовности DRDY
#define DEVICE_BUS_ERROR 2u // Бит статуса (0x02): сбой или таймаут транзакции на шине SPI при обращении к микросхеме
#define DEVICE_SENSOR_FAULT 4u // Бит статуса (0x04): микросхема MAX31865 зафиксировала обрыв или КЗ в цепи платинового датчика
#define DEVICE_INIT_ERROR 8u // Бит статуса (0x08): датчик не прошёл начальную конфигурацию или проверку Readback при старте
#define DEVICE_FILTER_WARMUP 16u // Бит статуса (0x10): цифровые фильтры (медиана/среднее) ещё накапливают выборку после старта или сброса
#define DEVICE_RANGE_ERROR 32u // Бит статуса (0x20): сопротивление или температура вышли за физические пределы модели (-200..+850 °C)
#define DEVICE_STOPPED 64u // Бит статуса (0x40): измерения остановлены либо данный канал не входит в число активных

// Структура привязки одного логического канала опроса к конкретному экземпляру драйвера и пину DRDY
typedef struct {
    max31865_t *device; // Указатель на контекст драйвера микросхемы MAX31865 данного канала
    void *ready_context; // Непрозрачный указатель на аппаратную структуру с портом и пином DRDY
    int (*ready)(void *); // Указатель на платформенную функцию проверки низкого уровня на линии DRDY
    uint8_t enabled; // Флаг разрешения работы: 1 — чип успешно инициализирован и включён, 0 — канал неисправен или отключён
} device_channel_t; // Имя типа структуры канала сборщика

// Настройки логики формирования кадра измерений
typedef struct {
    device_trigger_t trigger; // Выбранный режим синхронизации (DEVICE_WAIT_ALL или DEVICE_TRIGGER_FIRST)
    uint32_t timeout_ms; // Предельное время ожидания сигналов DRDY в мс, после которого кадр собирается принудительно
    uint8_t channel_mask; // Нулевое значение оставлено для старых вызывающих: все каналы до channel_count.
    uint8_t channel_count; // Количество активных каналов (от 1 до DEVICE_MAX_CHANNELS), участвующих в опросе
} device_settings_t; // Имя типа структуры настроек сборщика

// Результаты опроса и временной диагностики одного канала внутри собранного кадра
typedef struct {
    max31865_sample_t sample; // Сырой 15-битный код АЦП и байт аппаратных ошибок, прочитанные из MAX31865
    uint8_t status; // Битовая маска состояния канала (комбинация флагов DEVICE_*)
    uint32_t read_offset_ticks; // Задержка в тактах CPU от начала чтения кадра до старта SPI-транзакции этого канала
    uint32_t ready_offset_ticks; // Разброс времени готовности в тактах CPU относительно самого первого сработавшего DRDY в кадре
} device_channel_data_t; // Имя типа данных канала в кадре

// Полный синхронный снимок (кадр) одного цикла опроса всех каналов с меткой времени
typedef struct {
    device_channel_data_t channel[DEVICE_CHANNELS]; // Массив прочитанных данных и статусов по всем каналам платы
    uint32_t sequence; // Порядковый номер кадра с момента запуска текущего сеанса измерений
    uint32_t read_ticks; // Суммарная длительность последовательного чтения всех каналов по SPI в тактах ядра DWT
    uint32_t period_ticks; // Фактический период времени между началом прошлого и текущего кадра в тактах ядра
    uint32_t ready_span_ticks; // Максимальный разбег моментов появления DRDY между самым быстрым и самым медленным каналом в тактах
    uint8_t ready_mask; // Битовая маска каналов, успевших выставить сигнал DRDY до начала чтения по SPI
    uint32_t utc_seconds; // Календарный штамп времени кадра в секундах Unix UTC от модуля RTC
    uint16_t milliseconds; // Доля секунды штампа времени кадра (0..999 мс) из подсекундного регистра RTC->SSR
    uint8_t rtc_valid; // Флаг достоверности метки времени: 1 — часы RTC настроены и прочитаны без сбоев, 0 — время невалидно
} device_frame_t; // Имя типа структуры кадра измерений

// Главная структура состояния и накопленной диагностики модуля сбора данных
typedef struct {
    device_channel_t channel[DEVICE_CHANNELS]; // Массив дескрипторов привязки физических каналов
    device_settings_t settings; // Текущие настройки режима ожидания, таймаута и числа каналов
    void *clock_context; // Пользовательский контекст для функции чтения аппаратного таймера тактов
    uint32_t (*ticks)(void *); // Callback-функция получения текущего значения 32-битного счётчика тактов DWT->CYCCNT
    int (*timestamp)(uint32_t *, uint16_t *); // Callback-функция получения текущего времени UTC и миллисекунд из RTC
    uint32_t last_frame_ms; // Системное время в мс (HAL_GetTick) формирования предыдущего кадра для контроля таймаута
    uint32_t last_frame_ticks; // Значение счётчика тактов DWT в момент начала чтения предыдущего кадра
    uint32_t sequence; // Сквозной счётчик сформированных кадров
    uint32_t max_read_ticks; // Максимальное зафиксированное время SPI-чтения кадра в тактах CPU (для оценки худшей нагрузки)
    uint32_t timeout_frames; // Диагностический счётчик кадров, собранных принудительно по истечении таймаута ожидания DRDY
    uint32_t bus_errors[DEVICE_CHANNELS]; // Поканальные счётчики ошибок обмена по шине SPI
    uint32_t sensor_errors[DEVICE_CHANNELS]; // Поканальные счётчики аппаратных аварий термосопротивлений (обрыв/КЗ)
    uint32_t ready_ticks[DEVICE_CHANNELS]; // Зафиксированные метки времени DWT первого появления DRDY для каждого канала в текущем цикле
    uint32_t first_ready_ticks; // Метка времени DWT самого раннего сигнала DRDY в текущем цикле ожидания
    uint8_t observed_mask; // Битовая маска каналов, у которых уже был замечен и засечён по времени сигнал DRDY в текущем цикле
} device_acquisition_t; // Имя типа контекста сборщика

int device_acquisition_poll(device_acquisition_t *, uint32_t now_ms, device_frame_t *); // Прототип функции неблокирующего опроса DRDY и чтения кадра

#endif
