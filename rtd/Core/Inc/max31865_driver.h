#ifndef MAX31865_DRIVER_H
#define MAX31865_DRIVER_H

#include <stdint.h>
#include <stddef.h>

// Тип указателя на платформенную функцию полнодуплексного обмена по SPI: (контекст, буфер TX, буфер RX, длина в байтах) -> 0 при успехе
typedef int (*max31865_transfer_fn)(void *, const uint8_t *, uint8_t *, size_t);

// Структура состояния одного экземпляра драйвера датчика MAX31865
typedef struct {
    void *context; // Указатель на аппаратный контекст канала (порт/пин CS и дескриптор SPI)
    max31865_transfer_fn transfer; // Callback-функция выполнения SPI-транзакции с удержанием линии CS
    uint8_t config; // Теневая копия последнего подтверждённого значения регистра конфигурации (0x00) микросхемы
} max31865_t; // Имя типа контекста драйвера MAX31865

typedef int max31865_result_t; // Целочисленный тип для кодов возврата функций драйвера
#define MAX31865_OK 0 // Код возврата: операция обмена и верификации конфигурации прошла успешно
#define MAX31865_IO_ERROR 1 // Код возврата: аппаратная ошибка или таймаут на шине SPI
#define MAX31865_BAD_ARGUMENT 2 // Код возврата: в функцию передан нулевой указатель или недопустимый параметр (число проводов / частота фильтра)
#define MAX31865_CONFIG_ERROR 3 // Код возврата: прочитанный при проверке (Readback) байт конфигурации не совпал с записанным

#define MAX31865_BIAS 0x80u // Бит D7 регистра конфигурации: включение источника напряжения смещения Vbias на линии датчика
#define MAX31865_AUTO 0x40u // Бит D6 регистра конфигурации: режим непрерывных автоматических преобразований (1 — Auto, 0 — Normally Off)
#define MAX31865_THREE_WIRE 0x10u // Бит D4 регистра конфигурации: выбор схемы подключения (1 — 3-проводная схема, 0 — 2- или 4-проводная схема)
#define MAX31865_FILTER_50HZ 0x01u // Бит D0 регистра конфигурации: частота режекторного фильтра (1 — 50 Гц, 0 — 60 Гц)

#define MAX31865_FAULT_HIGH 0x80u // Бит D7 регистра Fault Status (0x07): измеренное сопротивление RTD превысило верхний порог High Fault Threshold (обрыв датчика)
#define MAX31865_FAULT_LOW 0x40u // Бит D6 регистра Fault Status (0x07): измеренное сопротивление RTD ниже нижнего порога Low Fault Threshold (КЗ датчика)
#define MAX31865_FAULT_REFIN_HIGH 0x20u // Бит D5 регистра Fault Status: напряжение REFIN- > 0.85 * Vbias (разомкнута цепь опорного резистора или датчика)
#define MAX31865_FAULT_REFIN_LOW 0x10u // Бит D4 регистра Fault Status: напряжение REFIN- < 0.85 * Vbias при принудительно разомкнутом ключе FORCE- (КЗ линии)
#define MAX31865_FAULT_SENSOR_LOW 0x08u // Бит D3 регистра Fault Status: напряжение RTDIN- < 0.85 * Vbias при разомкнутом ключе FORCE- (КЗ входа датчика на землю/питание)
#define MAX31865_FAULT_VOLTAGE 0x04u // Бит D2 регистра Fault Status: перенапряжение (Overvoltage) или пониженное напряжение (Undervoltage) на защитных диодах входов

#define MAX31865_CONFIG_WRITE 0x80u // Командный байт SPI для записи в регистр конфигурации 0x00 (установлен старший бит записи MSB = 1)
#define MAX31865_CONFIG_READ 0x00u // Командный байт SPI для чтения регистра конфигурации по адресу 0x00 (MSB = 0)
#define MAX31865_SAMPLE_READ 0x01u // Стартовый адрес для пакетного чтения регистров начиная с 0x01 (RTD MSB, RTD LSB, пороги и регистр ошибок 0x07)
#define MAX31865_CLEAR_FAULT 0x02u // Бит D1 регистра конфигурации: самосбрасывающийся бит очистки защёлкнутых флагов ошибок в регистре 0x07
#define MAX31865_PASSIVE_MASK (MAX31865_THREE_WIRE | MAX31865_FILTER_50HZ) // Маска пассивных битов конфигурации (сохраняет схему проводов и фильтр при выключении токов)
#define MAX31865_FAULT_MASK 0xfcu // Маска значимых диагностических битов (биты 7..2) регистра статуса ошибок 0x07 (отсекает резервные биты D1 и D0)

// Структура необработанного результата одного чтения датчика MAX31865
typedef struct {
    uint16_t raw; // Чистый 15-битный беззнаковый код АЦП (отношение Rrtd / Rref в диапазоне 0..32767)
    uint8_t sensor_fault; // Общий флаг аппаратной ошибки из младшего бита D0 регистра RTD LSB (0x02)
    uint8_t faults; // Детальная битовая маска аппаратных сбоев из регистра Fault Status (0x07), отфильтрованная по MAX31865_FAULT_MASK
} max31865_sample_t; // Имя типа структуры сырого отсчёта

max31865_result_t max31865_init(max31865_t *, void *, max31865_transfer_fn, unsigned wires, unsigned filter_hz); // Прототип функции начальной настройки датчика (Vbias и AUTO выключены)
max31865_result_t max31865_start(max31865_t *); // Прототип функции запуска непрерывных преобразований (включает биты Vbias и AUTO)
max31865_result_t max31865_bias(max31865_t *); // Прототип функции предварительного включения только тока смещения Vbias
max31865_result_t max31865_stop(max31865_t *); // Прототип функции отключения режима AUTO и снятия тока Vbias
max31865_result_t max31865_read(max31865_t *, max31865_sample_t *); // Прототип функции пакетного чтения 15-битного кода АЦП и регистров диагностики
max31865_result_t max31865_clear_faults(max31865_t *); // Прототип функции сброса защёлкнутых битов аппаратных ошибок датчика

#endif
