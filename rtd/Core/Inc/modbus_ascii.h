#ifndef MODBUS_ASCII_H
#define MODBUS_ASCII_H

#include <stddef.h>
#include <stdint.h>

#define MB_ADU_MAX 255u // Максимальный размер двоичного пакета ADU в байтах (Адрес + функциональный код + данные PDU + байт LRC)
#define MB_ASCII_MAX (MB_ADU_MAX * 2u + 3u) // Максимальная длина кодированного ASCII-кадра в байтах (513 символов: ':' + 255*2 HEX-символов + "\r\n")
#define MB_RX_SIZE 1024u // Размер приёмного кольцевого буфера в байтах (обязательно степень двойки для быстрого наложения битовой маски)
#define MB_POLL_BUDGET 256u // Максимальное количество символов, разбираемых из кольцевого буфера за один вызов функции poll в главном цикле
#define MB_CHARACTER_TIMEOUT_MS 1000u // Максимально допустимая пауза между символами одного кадра по стандарту Modbus ASCII (1 секунда = 1000 мс)
#define MB_COIL_ON 0xff00u // Константа включения одиночного флага Coil для функции 0x05 по стандарту Modbus (выключение передаётся как 0x0000)
#define MB_EXCEPTION_FLAG 0x80u // Битовая маска, добавляемая к коду функции (FC | 0x80) при формировании ответа об исключении (ошибке)
#define MB_ADDRESS_SPACE 65536u // Полная ёмкость 16-битного адресного пространства регистров Modbus (0..65535)
#define MB_READ_MAX 125u // Максимальное количество элементов, запрашиваемых за одну команду чтения в данной реализации (размер буфера стека)
#define MB_WRITE_MAX 123u // Максимальное количество регистров при групповой записи функцией 0x10 по стандарту Modbus

#define MB_FC_READ_COILS 1u // Код функции 0x01: Чтение группы битовых флагов (Read Coils)
#define MB_FC_READ_DISCRETE 2u // Код функции 0x02: Чтение дискретных входов (Read Discrete Inputs)
#define MB_FC_READ_HOLDING 3u // Код функции 0x03: Чтение регистров хранения настроек (Read Holding Registers)
#define MB_FC_READ_INPUT 4u // Код функции 0x04: Чтение входных регистров измерений (Read Input Registers)
#define MB_FC_WRITE_COIL 5u // Код функции 0x05: Запись одного битового флага (Write Single Coil)
#define MB_FC_WRITE_REGISTER 6u // Код функции 0x06: Запись одного регистра хранения (Write Single Register)
#define MB_FC_WRITE_COILS 15u // Код функции 0x0F (15): Запись группы битовых флагов (Write Multiple Coils)
#define MB_FC_WRITE_REGISTERS 16u // Код функции 0x10 (16): Запись группы регистров хранения (Write Multiple Registers)

#define MB_COILS 0u // Идентификатор адресного пространства Coils (чтение/запись битов) для прикладных колбэков
#define MB_DISCRETE 1u // Идентификатор адресного пространства Discrete Inputs (только чтение битов)
#define MB_HOLDING 2u // Идентификатор адресного пространства Holding Registers (чтение/запись 16-битных слов)
#define MB_INPUT 3u // Идентификатор адресного пространства Input Registers (только чтение 16-битных слов)

#define MB_ILLEGAL_FUNCTION 1 // Код исключения Modbus 0x01: Принятый код функции не поддерживается устройством
#define MB_ILLEGAL_ADDRESS 2 // Код исключения Modbus 0x02: Запрошенный адрес регистра не существует или выходит за допустимый диапазон
#define MB_ILLEGAL_VALUE 3 // Код исключения Modbus 0x03: Значение в поле данных недопустимо (ошибка длины пакета или границ параметра)
#define MB_DEVICE_FAILURE 4 // Код исключения Modbus 0x04: Невосстановимая аппаратная ошибка ведомого устройства
#define MB_DEVICE_BUSY 6 // Код исключения Modbus 0x06: Устройство занято выполнением долгой команды (например, записью во Flash или активным измерением)

// Тип callback-функции чтения карты регистров: (контекст, пространство, нач_адрес, количество, выходной_массив) -> 0 или код исключения
typedef int (*mb_read_fn)(void *, unsigned, uint16_t, uint16_t, uint16_t *);

// Тип callback-функции записи карты регистров: (контекст, пространство, нач_адрес, количество, входной_массив) -> 0 или код исключения
typedef int (*mb_write_fn)(void *, unsigned, uint16_t, uint16_t, const uint16_t *);

// Структура состояния транспортного уровня и парсера Modbus ASCII
typedef struct {
    volatile uint8_t ring[MB_RX_SIZE]; // Кольцевой буфер приёма сырых символов из прерывания USB CDC
    volatile uint8_t gap[MB_RX_SIZE]; // Параллельный массив признаков превышения межсимвольной паузы (>1000 мс) перед соответствующим байтом
    uint8_t received_once; // Флаг получения хотя бы одного пакета с момента старта (используется в прерывании для отсчёта пауз)
    volatile uint16_t head; // Индекс записи головы кольцевого буфера (изменяется только в прерывании USB)
    volatile uint16_t tail; // Индекс чтения хвоста кольцевого буфера (изменяется только в главном цикле)
    volatile uint8_t reset_requested; // Флаг запроса аварийного сброса буфера при переполнении или разрыве USB-соединения
    volatile uint32_t last_rx_ms; // Метка системного времени (мс) прихода последнего USB-фрагмента
    volatile uint32_t overflows; // Диагностический счётчик переполнений приёмного буфера
    uint8_t request[MB_ADU_MAX]; // Буфер накопления декодированных двоичных байтов текущего входящего запроса
    uint8_t response[MB_ASCII_MAX]; // Буфер сформированного текстового ASCII-ответа, ожидающего отправки в USB
    uint16_t request_length; // Текущее количество собранных байтов в буфере request
    uint16_t response_length; // Длина готового к отправке ответа в байтах (0 — если нет неотправленного ответа)
    uint8_t address; // Собственный сетевой адрес устройства Modbus (1..247)
    uint8_t collecting; // Флаг состояния парсера: 1 — встречен стартовый символ ':', идёт сборка кадра
    uint8_t half_byte; // Флаг сборки байта: 1 — принята старшая HEX-тетрада, ожидается младшая тетрада
    uint8_t high_nibble; // Временное хранилище старшей тетрады (сдвинутой на 4 бита влево) текущего собираемого байта
    uint8_t expect_lf; // Флаг завершения кадра: 1 — получен символ '\r' (CR), следующим символом обязан быть '\n' (LF)
    uint32_t lrc_errors; // Диагностический счётчик кадров, отброшенных из-за несовпадения контрольной суммы LRC
    uint32_t timeouts; // Диагностический счётчик кадров, оборванных по межсимвольному таймауту (>1 с)
    uint32_t requests; // Счётчик успешно принятых и адресованных данному устройству запросов
    uint32_t exceptions; // Счётчик ответов, завершившихся отправкой кода исключения Modbus
    void *context; // Указатель на прикладную структуру управления (передаётся в колбэки read и write)
    mb_read_fn read; // Указатель на функцию чтения регистров/битов устройства
    mb_write_fn write; // Указатель на функцию записи регистров/битов устройства
} modbus_ascii_t; // Имя типа структуры контекста Modbus ASCII

uint16_t modbus_crc16(const uint8_t *, size_t); // Прототип функции расчёта CRC-16 (используется для проверки целостности записей во Flash)
uint8_t modbus_lrc(const uint8_t *, size_t); // Прототип функции расчёта продольной контрольной суммы LRC для кадров Modbus ASCII
size_t modbus_ascii_encode(const uint8_t *, size_t, uint8_t *, size_t); // Прототип функции упаковки двоичного PDU в ASCII-кадр с расчётом LRC
void modbus_ascii_init(modbus_ascii_t *, uint8_t, void *, mb_read_fn, mb_write_fn); // Прототип функции инициализации контекста Modbus ASCII
void modbus_ascii_receive(modbus_ascii_t *, const uint8_t *, size_t, uint32_t); // Прототип функции приёма байтов из прерывания USB в кольцевой буфер
void modbus_ascii_disconnect(modbus_ascii_t *); // Прототип функции уведомления о разрыве связи USB
void modbus_ascii_poll(modbus_ascii_t *, uint32_t, void *, int (*send)(void *, const uint8_t *, size_t)); // Прототип фонового автомата разбора запросов и отправки ответов

#endif
